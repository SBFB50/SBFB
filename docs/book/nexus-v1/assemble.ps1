$ErrorActionPreference = "Stop"

$bookRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$destination = Join-Path $bookRoot "MANUSCRIT.md"

$entries = @(
    "_sections\cover.md",
    "00_note_au_lecteur.md",
    "_sections\part1.md",
    "01_le_monde_sous_location.md",
    "02_la_these_nexus.md",
    "03_une_journee_dans_nexus.md",
    "_sections\part2.md",
    "04_atelier_des_communs.md",
    "05_rrv.md",
    "06_conception.md",
    "_sections\part3.md",
    "07_workflow_hub.md",
    "08_factory.md",
    "09_reseau_apps_compute.md",
    "_sections\part4.md",
    "10_confiance_et_capacites.md",
    "11_gouvernance_sans_capture.md",
    "12_accessibilite.md",
    "13_ce_que_nexus_refuse.md",
    "_sections\part5.md",
    "14_projets_humanistes.md",
    "15_masse_engagee.md",
    "16_scenario_de_commun.md",
    "_sections\conclusion.md",
    "17_epilogue.md",
    "_sections\annexes.md",
    "90_glossaire.md",
    "91_carte_de_la_v1.md"
)

$chunks = [System.Collections.Generic.List[string]]::new()
$chunks.Add("<!-- Generated by assemble.ps1. Edit source chapters, not this file. -->")

foreach ($entry in $entries) {
    $sourcePath = Join-Path $bookRoot $entry
    if (-not (Test-Path -LiteralPath $sourcePath -PathType Leaf)) {
        throw "Missing chapter: $sourcePath"
    }

    $chunks.Add((Get-Content -Raw -Encoding UTF8 -LiteralPath $sourcePath).Trim())
}

$manuscript = ($chunks -join "`r`n`r`n---`r`n`r`n") + "`r`n"
$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($destination, $manuscript, $utf8NoBom)

$wordCount = ([regex]::Matches($manuscript, "\b[\p{L}\p{N}'-]+\b")).Count
$chapterCount = (
    Select-String -InputObject $manuscript -Pattern "(?m)^# Chapitre " -AllMatches
).Matches.Count

Write-Output "Manuscript: $destination"
Write-Output "Chapters: $chapterCount"
Write-Output "Approximate words: $wordCount"
